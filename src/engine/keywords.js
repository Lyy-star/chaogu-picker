function matchAny(text, words) {
  const hits = [];
  for (const w of words) if (text.includes(w)) hits.push(w);
  return hits;
}

/** 事件文本 -> 主题（可能多个） */
function themesOf(text) {
  const out = [];
  for (const entry of THEME_MAP) {
    const hits = matchAny(text, entry.keywords);
    if (hits.length) out.push({ theme: entry.theme, hits, boardHints: entry.boardHints });
  }
  return out;
}

